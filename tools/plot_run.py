def parse_data(raw_text):
    times = []
    raw_v = []
    filt_v = []
    base_v = []
    for line in raw_text.strip().split("\n"):
        parts = line.strip().split(",")
        if len(parts) >= 5:
            try:
                times.append(float(parts[0]))
                raw_v.append(float(parts[1]))
                filt_v.append(float(parts[2]))
                base_v.append(float(parts[3]))
            except ValueError:
                continue
    return np.array(times), np.array(raw_v), np.array(filt_v), np.array(base_v)

